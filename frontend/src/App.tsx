import { useState, useRef, type FormEvent } from "react";
import { useStream } from "@langchain/langgraph-sdk/react";

type ChatMessage = {
  id: string;
  role: "user" | "assistant";
  content: string;
};

type InterruptValue = {
  type?: string;
  restaurant?: string;
  restaurant_id?: string;
  date?: string;
  time?: string;
  party_size?: number;
  message?: string;
};

/*
 * Safely convert LangGraph message content into text.
 */
function getMessageText(content: unknown): string {
  if (typeof content === "string") {
    return content;
  }

  if (Array.isArray(content)) {
    return content
      .map((item) => {
        if (typeof item === "string") {
          return item;
        }

        if (item && typeof item === "object") {
          const value = item as Record<string, unknown>;

          if (typeof value.text === "string") {
            return value.text;
          }

          if (typeof value.content === "string") {
            return value.content;
          }
        }

        return "";
      })
      .filter(Boolean)
      .join("");
  }

  if (content && typeof content === "object") {
    const value = content as Record<string, unknown>;

    if (typeof value.text === "string") {
      return value.text;
    }

    if (typeof value.content === "string") {
      return value.content;
    }
  }

  return "";
}

/*
 * Internal messages generated by Reseva's planning/memory system.
 * These should never be shown to the customer.
 */
function isInternalMessage(text: string): boolean {
  const normalized = text.trim().toLowerCase();

  return (
    normalized.startsWith(
      "reseva long-term user preferences:"
    ) ||
    normalized.startsWith(
      "reseva execution plan:"
    ) ||
    normalized.includes("current user request:")
  );
}

/*
 * Detect messages generated by tools.
 *
 * Depending on the LangGraph/LangChain version,
 * tool messages can expose themselves as:
 *
 * - type: "tool"
 * - role: "tool"
 * - tool
 * - tool_result
 * - tool_call
 * - function
 */
function isToolMessage(
  value: Record<string, unknown>
): boolean {
  const type = String(value.type ?? "").toLowerCase();
  const role = String(value.role ?? "").toLowerCase();

  if (
    type === "tool" ||
    type === "tool_result" ||
    type === "tool_call" ||
    type === "function" ||
    role === "tool"
  ) {
    return true;
  }

  /*
   * Some streamed messages can expose tool calls
   * without using type === "tool".
   */
  if (Array.isArray(value.tool_calls)) {
    return true;
  }

  if (value.tool_call_id) {
    return true;
  }

  return false;
}

/*
 * Some tool outputs may arrive as JSON text even when
 * the SDK doesn't label them clearly as tool messages.
 *
 * We don't want raw internal JSON such as:
 *
 * {"available":true,"restaurant_id":"rest-001",...}
 *
 * appearing to customers.
 */
function looksLikeToolResult(text: string): boolean {
  const trimmed = text.trim();

  if (!trimmed.startsWith("{") || !trimmed.endsWith("}")) {
    return false;
  }

  try {
    const parsed = JSON.parse(trimmed);

    if (!parsed || typeof parsed !== "object") {
      return false;
    }

    const value = parsed as Record<string, unknown>;

    /*
     * Reservation/availability tool results commonly
     * contain fields such as these.
     */
    const toolLikeKeys = [
      "available",
      "restaurant_id",
      "reservation_id",
      "party_size",
      "booking_id",
      "slots",
      "availability",
    ];

    return toolLikeKeys.some(
      (key) => key in value
    );
  } catch {
    return false;
  }
}

function App() {
  const [input, setInput] = useState("");
  const [chatMessages, setChatMessages] = useState<
    ChatMessage[]
  >([]);

  const [isResponding, setIsResponding] =
    useState(false);

  /*
   * Prevent double-clicking Confirm/Cancel before
   * React has time to update isResponding.
   */
  const approvalInProgress = useRef(false);

  const stream = useStream({
    assistantId: "reseva",

    apiUrl:
      import.meta.env.VITE_LANGGRAPH_API_URL ||
      "http://127.0.0.1:2024",
  });

  /*
   * --------------------------------------------------
   * BUILD CUSTOMER-FACING ASSISTANT MESSAGES
   * --------------------------------------------------
   */
  const assistantMessages: ChatMessage[] = [];

  for (const message of stream.messages) {
    const value =
      message as unknown as Record<string, unknown>;

    const messageType = String(
      value.type ?? ""
    ).toLowerCase();

    const messageRole = String(
      value.role ?? ""
    ).toLowerCase();

    const text = getMessageText(
      value.content
    ).trim();

    /*
     * Ignore empty messages.
     */
    if (!text) {
      continue;
    }

    /*
     * Never display user messages coming from
     * LangGraph because we already display them
     * using local chatMessages.
     */
    if (
      messageType === "human" ||
      messageType === "user" ||
      messageRole === "user"
    ) {
      continue;
    }

    /*
     * IMPORTANT:
     * Hide tool calls/results.
     */
    if (isToolMessage(value)) {
      continue;
    }

    /*
     * Hide internal Reseva planning/memory.
     */
    if (isInternalMessage(text)) {
      continue;
    }

    /*
     * Hide raw JSON tool output.
     */
    if (looksLikeToolResult(text)) {
      continue;
    }

    /*
     * Avoid duplicate assistant messages.
     */
    const alreadyExists =
      assistantMessages.some(
        (existing) =>
          existing.content === text
      );

    if (alreadyExists) {
      continue;
    }

    assistantMessages.push({
      id: String(
        value.id ??
          `assistant-${assistantMessages.length}-${text.slice(
            0,
            20
          )}`
      ),
      role: "assistant",
      content: text,
    });
  }

  /*
   * Combine local user messages with the
   * customer-facing assistant messages.
   */
  const visibleMessages: ChatMessage[] = [
    ...chatMessages,
    ...assistantMessages,
  ];

  /*
   * --------------------------------------------------
   * LANGGRAPH INTERRUPT
   * --------------------------------------------------
   */
  const interrupt = stream.interrupt;

  const interruptValue =
    interrupt?.value as
      | InterruptValue
      | undefined;

  /*
   * --------------------------------------------------
   * SEND USER MESSAGE
   * --------------------------------------------------
   */
  const handleSubmit = async (
    e: FormEvent<HTMLFormElement>
  ) => {
    e.preventDefault();

    const message = input.trim();

    if (
      !message ||
      stream.isLoading ||
      isResponding
    ) {
      return;
    }

    /*
     * Display user message immediately.
     */
    setChatMessages((previous) => [
      ...previous,
      {
        id: `user-${Date.now()}`,
        role: "user",
        content: message,
      },
    ]);

    setInput("");

    try {
      await stream.submit({
        messages: [
          {
            content: message,
            type: "human",
          },
        ],
      });
    } catch (error) {
      console.error(
        "Reseva request failed:",
        error
      );
    }
  };

  /*
   * --------------------------------------------------
   * CONFIRM / CANCEL BOOKING
   * --------------------------------------------------
   *
   * Your current SDK uses:
   *
   * stream.submit(
   *   null,
   *   {
   *     command: {
   *       resume: true
   *     }
   *   }
   * )
   *
   * The resume value becomes the return value
   * of interrupt() inside the LangGraph node.
   */
  const handleApproval = async (
    approved: boolean
  ) => {
    /*
     * Stop duplicate clicks.
     */
    if (
      !interrupt ||
      approvalInProgress.current
    ) {
      return;
    }

    approvalInProgress.current = true;
    setIsResponding(true);

    console.log(
      "Reseva approval:",
      approved
    );

    try {
      /*
       * IMPORTANT:
       * Send the boolean directly.
       *
       * true  = approve booking
       * false = reject/cancel booking
       */
      await stream.submit(
        null,
        {
          command: {
            resume: approved,
          },
        }
      );
    } catch (error) {
      console.error(
        "Reseva approval response failed:",
        error
      );
    } finally {
      approvalInProgress.current = false;
      setIsResponding(false);
    }
  };

  /*
   * --------------------------------------------------
   * UI
   * --------------------------------------------------
   */
  return (
    <main className="min-h-screen bg-[#f7f5f0] text-[#171717] flex flex-col items-center px-6">

      {/* Header */}
      <header className="pt-12 sm:pt-16">
        <div className="flex items-center gap-3">
          <div className="flex h-10 w-10 items-center justify-center rounded-full bg-black text-xl font-semibold text-white">
            R
          </div>

          <h1 className="text-3xl sm:text-4xl font-semibold tracking-[0.3em]">
            ESEVA
          </h1>
        </div>
      </header>

      {/* Main */}
      <section className="flex flex-1 w-full max-w-3xl flex-col items-center justify-center -mt-10">

        {/* Customer-facing conversation */}
        {visibleMessages.length > 0 ? (
          <div className="mb-6 w-full max-w-2xl space-y-3">

            {visibleMessages.map(
              (message) => (
                <div
                  key={`${message.role}-${message.id}`}
                  className={`flex ${
                    message.role === "user"
                      ? "justify-end"
                      : "justify-start"
                  }`}
                >
                  <div
                    className={`max-w-[85%] rounded-2xl px-4 py-3 text-sm leading-6 ${
                      message.role === "user"
                        ? "bg-black text-white"
                        : "border border-black/5 bg-white shadow-sm"
                    }`}
                  >
                    {message.content}
                  </div>
                </div>
              )
            )}

          </div>
        ) : null}

        {/* 
          BOOKING CONFIRMATION

          Only ONE interrupt card is rendered.
          We do NOT render it inside stream.messages.
        */}
        {interruptValue?.message ? (
          <div className="mb-6 w-full max-w-2xl rounded-2xl border border-black/5 bg-white p-5 shadow-sm">

            <p className="text-sm leading-6">
              {interruptValue.message}
            </p>

            {/* Optional booking details */}
            {(interruptValue.restaurant ||
              interruptValue.date ||
              interruptValue.time ||
              interruptValue.party_size) ? (
              <div className="mt-4 rounded-xl bg-[#f7f5f0] p-4 text-sm">

                {interruptValue.restaurant ? (
                  <p>
                    <span className="font-medium">
                      Restaurant:
                    </span>{" "}
                    {interruptValue.restaurant}
                  </p>
                ) : null}

                {interruptValue.party_size ? (
                  <p>
                    <span className="font-medium">
                      Guests:
                    </span>{" "}
                    {interruptValue.party_size}
                  </p>
                ) : null}

                {interruptValue.date ? (
                  <p>
                    <span className="font-medium">
                      Date:
                    </span>{" "}
                    {interruptValue.date}
                  </p>
                ) : null}

                {interruptValue.time ? (
                  <p>
                    <span className="font-medium">
                      Time:
                    </span>{" "}
                    {interruptValue.time}
                  </p>
                ) : null}

              </div>
            ) : null}

            {/* Buttons */}
            <div className="mt-5 flex flex-wrap gap-3">

              {/* Confirm */}
              <button
                type="button"
                onClick={() =>
                  handleApproval(true)
                }
                disabled={
                  isResponding
                }
                className="rounded-full bg-black px-5 py-2.5 text-sm font-medium text-white transition hover:scale-[1.02] disabled:cursor-not-allowed disabled:opacity-50"
              >
                {isResponding
                  ? "Processing..."
                  : "Confirm booking"}
              </button>

              {/* Cancel */}
              <button
                type="button"
                onClick={() =>
                  handleApproval(false)
                }
                disabled={
                  isResponding
                }
                className="rounded-full border border-black/10 bg-white px-5 py-2.5 text-sm font-medium text-black transition hover:bg-black/5 disabled:cursor-not-allowed disabled:opacity-50"
              >
                Cancel
              </button>

            </div>
          </div>
        ) : null}

        {/* Input */}
        <div className="w-full max-w-2xl">

          <form
            onSubmit={handleSubmit}
            className="flex items-center gap-3 rounded-2xl border border-black/10 bg-white px-4 py-3 shadow-lg"
          >

            <input
              type="text"
              value={input}
              onChange={(e) =>
                setInput(e.target.value)
              }
              placeholder="Start booking..."
              disabled={
                stream.isLoading ||
                isResponding ||
                !!interruptValue
              }
              className="flex-1 bg-transparent text-sm outline-none placeholder:text-black/35 disabled:opacity-50"
            />

            <button
              type="submit"
              disabled={
                stream.isLoading ||
                isResponding ||
                !!interruptValue ||
                !input.trim()
              }
              className="flex h-10 w-10 shrink-0 items-center justify-center rounded-full bg-black text-white transition hover:scale-105 disabled:cursor-not-allowed disabled:opacity-40"
              aria-label="Send message"
            >
              →
            </button>

          </form>
        </div>

        {/* Tagline */}
        {visibleMessages.length === 0 &&
        !interruptValue ? (
          <p className="mt-8 max-w-2xl text-center text-lg font-semibold tracking-wide text-black/70">
            Your AI reservation assistant to restaurants and fine cuisines.
          </p>
        ) : null}

        {/* Loading */}
        {stream.isLoading ? (
          <p className="mt-4 text-xs text-black/40">
            ResEva is thinking...
          </p>
        ) : null}

        {/* Error */}
        {!!stream.error ? (
          <p className="mt-4 max-w-2xl text-center text-sm text-red-600">
            Something went wrong. Please try again.
          </p>
        ) : null}

      </section>

      {/* Footer */}
      <footer className="pb-8 text-xs text-black/25">
        Powered by AI
      </footer>

    </main>
  );
}

export default App;